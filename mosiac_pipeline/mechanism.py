"""Stages 1-4: construct, explain, calibrate and reduce a gas-phase reaction mechanism (Cantera-backed).

Everything here is exercised by run_end_to_end.py on the published H2/O2 mechanism (Cantera's h2o2.yaml).
The calibration stage is a *synthetic twin experiment* (targets generated from a deliberately perturbed copy of
the mechanism), because no experimental data set is bundled with this demo.
"""
from __future__ import annotations

import numpy as np
import cantera as ct
from scipy.optimize import least_squares

FUEL, OXIDIZER = "H2:1", "O2:1, N2:3.76"
P0 = ct.one_atm
# (T0 [K], equivalence ratio) conditions used for calibration / reduction checks
CONDITIONS = [(T, phi) for T in (1000.0, 1100.0, 1250.0, 1400.0) for phi in (0.7, 1.0, 1.3)]


# ------------------------------------------------------------------ stage 1: construct
def construct(path: str = "h2o2.yaml") -> tuple[ct.Solution, dict]:
    """Load a mechanism and check it is physically well-formed (every reaction conserves every element)."""
    gas = ct.Solution(path)
    atoms = np.array([[gas.n_atoms(k, m) for m in range(gas.n_elements)] for k in range(gas.n_species)], float)
    delta = atoms.T @ (gas.product_stoich_coeffs - gas.reactant_stoich_coeffs)
    report = {
        "source": path,
        "species": list(gas.species_names),
        "n_reactions": gas.n_reactions,
        "elements": list(gas.element_names),
        "element_imbalance_max": float(np.abs(delta).max()),
    }
    if report["element_imbalance_max"] > 1e-9:
        raise ValueError(f"mechanism violates element conservation: {report['element_imbalance_max']}")
    return gas, report


# ------------------------------------------------------------------ shared: ignition delay
def ignition_delay(gas: ct.Solution, T0: float, phi: float, P: float = P0, rise: float = 400.0, t_max: float = 0.2) -> float:
    """Time at which temperature has risen by `rise` K in a constant-pressure adiabatic reactor (linear interpolation).

    A threshold-crossing time is used instead of the max-gradient time because it is smooth in the rate parameters,
    which matters for the least-squares calibration below.
    """
    gas.set_equivalence_ratio(phi, FUEL, OXIDIZER)
    gas.TP = T0, P
    r = make_reactor(gas)
    net = ct.ReactorNet([r])
    net.rtol, net.atol = 1e-9, 1e-15
    t_prev, T_prev = 0.0, T0
    while net.time < t_max:
        t = net.step()
        T = r.T
        if T >= T0 + rise:
            return t_prev + (t - t_prev) * (T0 + rise - T_prev) / (T - T_prev)
        t_prev, T_prev = t, T
    return float("nan")


def make_reactor(gas: ct.Solution) -> ct.IdealGasConstPressureReactor:
    """Constant-pressure reactor that uses `gas` itself (Cantera >= 3.1 clones by default, older versions do not)."""
    try:
        return ct.IdealGasConstPressureReactor(gas, clone=False)
    except TypeError:
        return ct.IdealGasConstPressureReactor(gas)


def delays(gas: ct.Solution, conds=CONDITIONS) -> np.ndarray:
    return np.array([ignition_delay(gas, T, phi) for T, phi in conds])


def set_multipliers(gas: ct.Solution, mult: np.ndarray) -> None:
    for i, m in enumerate(mult):
        gas.set_multiplier(float(m), i)


# ------------------------------------------------------------------ stage 2: explain
def explain(gas: ct.Solution, T0: float = 1100.0, phi: float = 1.0, top: int = 6, eps: float = 1.05) -> dict:
    """Brute-force sensitivity of ignition delay to every reaction's rate: d ln(tau) / d ln(k)."""
    set_multipliers(gas, np.ones(gas.n_reactions))
    tau0 = ignition_delay(gas, T0, phi)
    sens = np.zeros(gas.n_reactions)
    for i in range(gas.n_reactions):
        gas.set_multiplier(eps, i)
        sens[i] = np.log(ignition_delay(gas, T0, phi) / tau0) / np.log(eps)
        gas.set_multiplier(1.0, i)
    order = np.argsort(-np.abs(sens))
    return {
        "condition": {"T0": T0, "phi": phi, "tau_s": tau0},
        "sensitivity": sens,
        "top": [{"index": int(i), "reaction": gas.reaction(int(i)).equation, "dln_tau_dln_k": float(sens[i])} for i in order[:top]],
    }


# ------------------------------------------------------------------ stage 3: calibrate (synthetic twin experiment)
def calibrate_twin(gas: ct.Solution, sens: np.ndarray, n_params: int = 4, truth_log: tuple = (0.35, -0.30, 0.25, -0.20)) -> dict:
    """Recover rate multipliers from ignition-delay targets generated by a perturbed copy of the mechanism.

    Honest scope: targets are synthetic, so this shows the inverse problem is posed and solved correctly
    (and how well the parameters are identifiable), not agreement with a real experiment.
    """
    n = gas.n_reactions
    idx = np.argsort(-np.abs(sens))[:n_params]
    truth = np.ones(n)
    truth[idx] = np.exp(np.array(truth_log[:n_params]))
    set_multipliers(gas, truth)
    targets = delays(gas)
    set_multipliers(gas, np.ones(n))
    tau_start = delays(gas)

    def residual(x):
        m = np.ones(n)
        m[idx] = np.exp(x)
        set_multipliers(gas, m)
        return np.log(delays(gas)) - np.log(targets)

    x0 = np.zeros(n_params)
    res = least_squares(residual, x0, bounds=(-1.2, 1.2), diff_step=1e-2, xtol=1e-6, ftol=1e-8)
    fitted = np.ones(n)
    fitted[idx] = np.exp(res.x)
    set_multipliers(gas, fitted)
    tau_fit = delays(gas)
    rms = lambda a: float(np.sqrt(np.mean((np.log(a) - np.log(targets)) ** 2)))
    return {
        "calibrated_reactions": [gas.reaction(int(i)).equation for i in idx],
        "truth_multipliers": truth[idx].tolist(),
        "recovered_multipliers": fitted[idx].tolist(),
        "rms_log_error_before": rms(tau_start),
        "rms_log_error_after": rms(tau_fit),
        "multipliers": fitted,
        "note": "synthetic twin experiment; multipliers of correlated reactions need not be recovered individually",
    }


# ------------------------------------------------------------------ stage 4: reduce
def build_subset(gas: ct.Solution, keep: list[int], mult: np.ndarray) -> ct.Solution:
    reactions = [gas.reaction(i) for i in keep]
    red = ct.Solution(thermo="ideal-gas", kinetics="gas", species=gas.species(), reactions=reactions)
    for j, i in enumerate(keep):
        red.set_multiplier(float(mult[i]), j)
    return red


def reduce_reactions(gas: ct.Solution, mult: np.ndarray, tol_single: float = 0.005, tol_total: float = 0.03) -> dict:
    """Drop reactions whose removal barely changes ignition delay, then verify the combined error."""
    n = gas.n_reactions
    set_multipliers(gas, mult)
    ref = delays(gas)
    single = np.zeros(n)
    for i in range(n):
        gas.set_multiplier(0.0, i)
        single[i] = np.nanmax(np.abs(delays(gas) / ref - 1.0))
        gas.set_multiplier(float(mult[i]), i)
    droppable = [i for i in np.argsort(single) if single[i] < tol_single]
    keep = [i for i in range(n) if i not in droppable]
    while True:
        red = build_subset(gas, keep, mult)
        err = float(np.nanmax(np.abs(delays(red) / ref - 1.0)))
        if err <= tol_total or not droppable:
            break
        back = droppable.pop()  # restore the most influential dropped reaction
        keep = sorted(keep + [back])
    return {
        "kept": keep,
        "dropped": [gas.reaction(i).equation for i in range(n) if i not in keep],
        "n_full": n,
        "n_reduced": len(keep),
        "max_rel_delay_error": err,
        "tolerance": tol_total,
        "mechanism": red,
    }
